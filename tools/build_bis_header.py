#!/usr/bin/env python3
"""Generate the runtime item/state union from the reviewed factual catalog."""
import argparse
import csv
import pathlib


def render(catalog):
    masks = {}
    with pathlib.Path(catalog).open() as f:
        for row in csv.DictReader(f, delimiter='\t'):
            item = int(row['item_id'])
            mask = 0
            for state in row['progression_states'].split(','):
                state = int(state)
                if not 0 <= state <= 18:
                    raise ValueError('Invalid Individual Progression state')
                mask |= 1 << state
            masks[item] = masks.get(item, 0) | mask
    entries = '\n'.join('    {%d, 0x%05xu},' % pair for pair in sorted(masks.items()))
    return '''// Generated by tools/build_bis_header.py from data/progression-bis/catalog.tsv.
// Factual published selections and source receipts are retained in data/progression-bis/.
#ifndef AH_BOT_PROGRESSION_BIS_H
#define AH_BOT_PROGRESSION_BIS_H
#include <algorithm>
#include <array>
#include <cstdint>
namespace AhBotPricing
{
struct BisEntry { std::uint32_t item; std::uint32_t states; };
inline constexpr std::array<BisEntry, %d> ProgressionBis = {{
%s
}};
inline bool IsProgressionBis(std::uint32_t item)
{
    auto it = std::lower_bound(ProgressionBis.begin(), ProgressionBis.end(), item,
        [](BisEntry const& entry, std::uint32_t id) { return entry.item < id; });
    return it != ProgressionBis.end() && it->item == item;
}
}
#endif
''' % (len(masks), entries)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', default='data/progression-bis/catalog.tsv')
    parser.add_argument('--header', default='src/ProgressionBis.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(args.catalog)
    if args.check:
        if pathlib.Path(args.header).read_text() != text:
            raise SystemExit('Generated BiS header is stale')
    else:
        pathlib.Path(args.header).write_text(text)
